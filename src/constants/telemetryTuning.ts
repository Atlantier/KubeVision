/* ========================================================================== */
/* 健康区间与告警阈值                                                           */
/* ========================================================================== */

/**
 * 节点健康区间（%，CPU 与内存共用）。
 *
 * 【观感影响】这是**视觉安全区**：
 * - 低于 24%：柱体太矮，画面像空载，观众会觉得"这台机器没事干"；
 * - 高于 56%：已经接近琥珀色的心理阈值，稳态就偏黄会让人误以为有异常。
 * 因此所有角色基线（36~48）都刻意收在区间中段：最靠边的 48 距上界 56 仍留 8 个
 * 百分点，正好覆盖噪声的 3σ 摆动（实测 300 tick 内所有采样都在 24~56 内，
 * 仅内存型节点的瞬时峰值 56.2 擦过一次上界）。
 */
export const NODE_HEALTHY_MIN = 24;
export const NODE_HEALTHY_MAX = 56;

/**
 * 高负载（HighLoad）判定阈值。
 *
 * 【观感影响】CPU ≥ 85 或内存 ≥ 88 时节点转琥珀态。
 * 取 85/88 而不是 70：稳态基线最高才 54，留出 30 多个百分点的缓冲，
 * 保证正常波动（±12）绝不会误触发琥珀；同时故障态（CPU 92~99、内存 88~99）
 * 一定越线，颜色语义干净利落、不出现"半红不红"的中间态。
 */
export const NODE_HIGH_LOAD_CPU = 85;
export const NODE_HIGH_LOAD_MEM = 88;

/* ========================================================================== */
/* 均值回归与噪声                                                               */
/* ========================================================================== */

/**
 * 节点均值回归速率（每 tick 向基线靠拢的比例）。
 *
 * next = current + (baseline − current) · RATE + noise
 *
 * 【观感影响】
 * - 调大（如 0.35）：偏离被迅速抹平，柱子几乎纹丝不动 → 画面"死"，像静态图；
 * - 调小（如 0.08）：回归太慢，视觉上像迟钝的漂移，且故障恢复要等十几秒才回落；
 * - 0.18：故障解除后约 10 帧回到基线附近（≈10 秒），观众能看清"恢复过程"，
 *   稳态仍有轻微呼吸感。与 Pod 侧 REVERSION_RATE 同值，保证两类实体节奏一致。
 */
export const NODE_REVERSION_RATE = 0.18;

/**
 * 节点 CPU 噪声幅度（百分点，每 tick 叠加的零均值扰动）。
 *
 * 【观感影响】与回归速率共同决定稳态波动幅度：
 * 稳态标准差 ≈ 幅度 / √(2·RATE − RATE²)，0.18 时约等于 幅度 × 1.75。
 * - 2.2 → 稳态波动约 ±4 个百分点，峰谷差约 ±11：柱子有轻微呼吸感但不晃眼；
 * - 调到 5 以上 → 峰谷差超过 25 个百分点，正常态看起来像"一直在抖"；
 * - 调到 1 以下 → 柱子几乎不动，失去"活数据"的观感。
 * 节点取 2.2 略小于 Pod 的 2.6，因为节点是聚合量，本就应比单个 Pod 平稳。
 */
export const NODE_CPU_NOISE_AMPLITUDE = 2.2;

/**
 * 节点内存噪声幅度（百分点）。
 *
 * 【观感影响】内存柱对视觉的干扰比 CPU 更强（高度差更显眼），故取 1.6，
 * 约为 CPU 的 73%：既保留呼吸感，又不让内存柱在稳态下明显上下跳。
 */
export const NODE_MEM_NOISE_AMPLITUDE = 1.6;

/* ========================================================================== */
/* 过阻尼保护（一阶差分限幅）                                                    */
/* ========================================================================== */

/**
 * 单 tick 允许的最大 CPU 变化量（百分点）——"过阻尼保护"。
 *
 * 【解决什么问题】故障解除的那一瞬间，节点值从故障态（如 CPU 95）被直接
 * 拉回基线（46）。若回归项或噪声叠加后的一阶差分过大，画面上就是一帧跳变：
 * 柱子从红区"啪"地掉到绿区，趋势图出现垂直断崖——观众会以为画面出 bug。
 *
 * 【为什么是 6】正常回归的理论最大步长为 RATE × 最大偏差：
 * 0.18 × (95 − 46) ≈ 8.8。取 6 意味着**最陡的下降沿被削平**（8.8 → 6），
 * 且只在极端偏离后的前 1~2 帧生效；后续自然步长迅速小于 6，不会拖慢恢复。
 * 调大（≥9）保护形同虚设；调小（≤3）恢复会明显变慢、看起来像卡住。
 */
export const NODE_MAX_STEP_CPU = 6;

/**
 * 单 tick 允许的最大内存变化量（百分点）。
 *
 * 【观感影响】内存柱比 CPU 柱更高更显眼，跳变更容易被察觉，故限幅更严（5）。
 * 0.18 × (88 − 54) ≈ 6.1 → 首帧被削到 5，下降沿更平顺。
 */
export const NODE_MAX_STEP_MEM = 5;

/* ========================================================================== */
/* 兜底基线（live 模式真实节点名不在角色表内时）                                  */
/* ========================================================================== */

/**
 * 兜底基线区间（%）：live 模式下真实集群节点名无法映射到角色时，
 * 用 nodeId 的 FNV-1a 哈希在这个区间内取一个**确定性**值。
 *
 * 【为什么不用 Math.random】同一台机器每次刷新必须显示同一个基线，
 * 否则"刚才还是 40%，刷新变 31%"会让人怀疑数据是编的。
 *
 * 【观感影响】区间收窄到健康区间的中段（28~52），保证兜底节点也不会
 * 贴边触发琥珀，同时同一次会话内每台机器有独立且稳定的水位。
 */
export const NODE_FALLBACK_CPU_MIN = 28;
export const NODE_FALLBACK_CPU_MAX = 52;
export const NODE_FALLBACK_MEM_MIN = 28;
export const NODE_FALLBACK_MEM_MAX = 52;

/* ========================================================================== */
/* 自愈免疫窗口（store 去重 + Hook 视觉保持的唯一事实源）                          */
/* ========================================================================== */

/**
 * 自愈免疫窗口（毫秒）—— 同一 targetId 在此窗口内：
 * 1. store.healEntity 拒绝重复自愈（去重，防告警风暴期反复重启同一 Pod）；
 * 2. useTelemetryStream.reconcileSnapshot 把该 Pod 的展示值强制保持在健康区间
 *    （视觉保持，不被服务端仍在下发的故障帧立即推翻）。
 *
 * 【为什么必须单常量（R3）】此前 store 用 30s、Hook 用 15s：第 16~30 秒之间
 * 3D 视口已回落故障态，动作卡却仍提示「免疫窗口内不可重复自愈，剩余 N 秒」——
 * 同一屏两个事实。统一后「剩余秒数提示」与「视觉免疫」严格同生共死。
 *
 * 【为什么是 15s 而不是 30s】视觉保持只需覆盖「服务端故障帧停止下发 + 本地
 * 演进收敛回健康」的过渡期（混沌注入随自愈复位为 NONE，约 2~3 个 tick 收敛）；
 * 15s 已留 5 倍余量。窗口越长，新注入故障被旧免疫表掩盖的时间越长——
 * 15s 是「看得见的自愈成效」与「不掩盖新故障」的平衡点。
 * 探针契约：probe-r13 以 14400ms 前移免疫起点验证到期平滑回落，依赖本值 15000。
 */
export const HEAL_IMMUNITY_WINDOW_MS = 15_000;